# Dumps the IQ2_XXS (256 x 8) and IQ2_S (1024 x 8) lattice magnitudes via the gguf-py oracle into src/quant_iq2_grids.rs.
import sys, numpy as np
sys.path.insert(0, sys.argv[1])
from gguf import quants
with open(sys.argv[2], 'w') as f:
    f.write("// Generated by tools/gen_iq2_grids.py: IQ2_XXS / IQ2_S lattice magnitudes (format constants; see NOTICE).\n")
    for nm, cls, n in (("IQ2XXS_GRID", quants.IQ2_XXS, 256), ("IQ2S_GRID", quants.IQ2_S, 1024)):
        cls.init_grid()
        g = cls.grid.reshape(n, 8).astype(np.uint8)
        f.write("pub const %s: [[u8; 8]; %d] = [\n" % (nm, n))
        for r in g: f.write("    [%s],\n" % ", ".join(str(int(x)) for x in r))
        f.write("];\n")
