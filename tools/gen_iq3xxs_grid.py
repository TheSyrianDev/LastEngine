# Dumps the IQ3_XXS lattice (256 x 4 magnitudes) via the gguf-py oracle into src/quant_iq3xxs_grid.rs.
import sys, numpy as np
sys.path.insert(0, sys.argv[1])
from gguf import quants
q = quants.IQ3_XXS; q.init_grid()
g = q.grid.reshape(256, 4).astype(np.uint8)
with open(sys.argv[2], 'w') as f:
    f.write("// Generated by tools/gen_iq3xxs_grid.py: IQ3_XXS lattice magnitudes (format constant; see NOTICE).\n")
    f.write("pub const IQ3XXS_GRID: [[u8; 4]; 256] = [\n")
    for r in g: f.write("    [%d, %d, %d, %d],\n" % tuple(r))
    f.write("];\n")
